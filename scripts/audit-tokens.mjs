// npm run audit:tokens: the token inventory and the literal-geometry census (TOKENS.md, A-02).
// check-tokens.mjs says what is forbidden (hex, arbitrary values, off-grid spacing). This says
// what is *named* and what isn't: every variable theme.css defines and how often each is used
// outside it, and every numeric Tailwind utility (h-11, size-4, pl-13, rounded-md, opacity-75,
// bg-overlay/8…) the Paige layer writes by hand, tallied by value and by file, so a value that
// recurs across files shows up as a token that doesn't exist yet. Everything is grep-level, as
// check-tokens.mjs is.
//   node scripts/audit-tokens.mjs            writes TOKENS.md between the tokens markers
//   node scripts/audit-tokens.mjs --print    prints the sections instead
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, relative, sep } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const ui = join(root, "packages/ui/src")
const theme = join(ui, "theme.css")
const START = "<!-- tokens:start (generated by `npm run audit:tokens`; do not edit by hand) -->"
const END = "<!-- tokens:end -->"

const walk = (dir) =>
  readdirSync(dir).flatMap((n) => {
    if (n === "node_modules" || n === ".next" || n === "storybook-static") return []
    const p = join(dir, n)
    return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|css|mdx)$/.test(n) ? [p] : []
  })
const read = (f) => readFileSync(f, "utf8").replace(/\r\n/g, "\n")
const rel = (f) => relative(root, f).split(sep).join("/")

// lib/ is left out of the census: utils.test.ts names every utility to test the merge registry.
const paige = [...walk(ui), ...walk(join(root, "apps/web"))].filter((f) => f !== theme && !f.includes(`${sep}base${sep}`) && !f.includes(`${sep}lib${sep}`))
const upstream = walk(join(ui, "base"))
const sources = paige.map((f) => ({ f, s: read(f), story: /\.stories\.tsx$|[\\/]stories[\\/]|[\\/]foundations[\\/]/.test(f) }))

// ── 1. Theme inventory ─────────────────────────────────────────────────────────────────────────
const css = read(theme)
const layers = []
{
  const re = /\/\* -{6,} (\d) · ([^-]+?) -{6,}/g
  let m
  while ((m = re.exec(css))) layers.push({ n: m[1], name: m[2].trim(), at: m.index })
}
const layerAt = (i) => layers.filter((l) => l.at <= i).pop()?.n ?? "0"
const defs = []
{
  const re = /^\s*(--[\w-]+):\s*([^;]+);/gm
  let m
  while ((m = re.exec(css))) {
    const name = m[1]
    if (name.endsWith("-*")) continue
    const layer = layerAt(m.index)
    if (defs.some((d) => d.name === name && d.layer === layer)) continue // breakpoint overrides of --gutter
    defs.push({ name, value: m[2].trim().replace(/\s+/g, " "), layer })
  }
}

/** The utility classes a @theme inline variable produces, as a regex over a class string. */
function utilityRe(name) {
  const [, ns, key] = /^--(color|spacing|text|radius|shadow|container|font-weight|font|tracking|leading|breakpoint|animate)-(.+)$/.exec(name) ?? []
  if (!ns) return null
  const k = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
  const pre = String.raw`(?<![\w-])(?:[\w\[\]=:-]+:)*(?:-)?`
  const post = String.raw`(?![\w-])`
  switch (ns) {
    case "color":
      return new RegExp(`${pre}(?:bg|text|border(?:-[xytblrse])?|ring|ring-offset|outline|fill|stroke|from|via|to|decoration|accent|caret|divide|shadow|placeholder|inset-ring)-${k}(?:/\\d+)?${post}`, "g")
    case "spacing":
      return new RegExp(`${pre}(?:p[xytblrse]?|m[xytblrse]?|gap(?:-[xy])?|space-[xy]|w|h|size|min-w|max-w|min-h|max-h|inset(?:-[xy])?|top|left|right|bottom|start|end|basis|translate(?:-[xy])?|scroll-m[xytblr]?|scroll-p[xytblr]?|indent)-${k}${post}`, "g")
    case "text":
      return new RegExp(`${pre}text-${k}${post}`, "g")
    case "radius":
      return new RegExp(`${pre}rounded(?:-[tblrse]{1,2})?-${k}${post}`, "g")
    case "shadow":
      return new RegExp(`${pre}(?:shadow|inset-shadow|drop-shadow)-${k}${post}`, "g")
    case "container":
      return new RegExp(`${pre}(?:max-w|w|min-w|@container|@)-${k}${post}`, "g")
    case "font-weight":
      return new RegExp(`${pre}font-${k}${post}`, "g")
    case "font":
      return new RegExp(`${pre}font-${k}${post}`, "g")
    case "tracking":
      return new RegExp(`${pre}tracking-${k}${post}`, "g")
    case "leading":
      return new RegExp(`${pre}leading-${k}${post}`, "g")
    case "breakpoint":
      return new RegExp(`(?<![\\w-])(?:max-)?${k}:`, "g")
    case "animate":
      return new RegExp(`${pre}animate-${k}${post}`, "g")
    default:
      return null
  }
}

const baseSources = upstream.map((f) => ({ f, s: read(f) }))
const inventory = defs.map((d) => {
  const direct = new RegExp(`var\\(${d.name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[,)]`, "g")
  const util = utilityRe(d.name)
  const count = (s) => (s.match(direct) ?? []).length + (util ? (s.match(util) ?? []).length : 0)
  let uses = 0
  const files = new Set()
  for (const { f, s } of sources) {
    const n = count(s)
    if (n) {
      uses += n
      files.add(rel(f))
    }
  }
  let inBase = 0
  for (const { s } of baseSources) inBase += count(s)
  const inTheme = count(css) // var(--x) in another role, or the utility in an @apply
  // Tailwind's --text-xs--line-height is consumed with its parent; its --default-* keys
  // (--default-transition-duration, --default-font-family…) are read by the core utilities.
  const subProperty = /--[\w-]+--[\w-]+$/.test(d.name) || d.name.startsWith("--default-")
  return { ...d, uses, files: [...files], inBase, inTheme, subProperty }
})
const aliased = new Set(inventory.filter((d) => d.layer === "4").map((d) => /var\((--[\w-]+)\)/.exec(d.value)?.[1]).filter(Boolean))
// A role whose utility alias is used in Paige code (`--sidebar-border` via `border-sidebar-border`) is
// used in Paige code, even when its only direct `var()` reference sits in a base file.
const aliasUsed = new Set(inventory.filter((d) => d.layer === "4" && d.uses > 0).map((d) => /var\((--[\w-]+)\)/.exec(d.value)?.[1]).filter(Boolean))
for (const d of inventory) d.viaUtility = aliased.has(d.name)
const dead = inventory.filter((d) => d.uses === 0 && d.inBase === 0 && d.inTheme === 0 && !d.viaUtility && !d.subProperty)
const baseOnly = inventory.filter((d) => d.uses === 0 && d.inBase > 0 && !aliasUsed.has(d.name))
const rawOutside = inventory.filter((d) => d.layer === "1" && d.uses > 0)
const themeOnly = inventory.filter((d) => d.uses === 0 && d.inBase === 0 && (d.inTheme > 0 || d.viaUtility))

const invTable = [
  "| Layer | Variable | Value | Uses in Paige code | Files | Uses in base | Inside theme.css |",
  "|---|---|---|---|---|---|---|",
  ...inventory.map((d) => `| ${d.layer} | \`${d.name}\` | \`${d.value.replace(/\|/g, "\\|")}\` | ${d.uses}${d.viaUtility ? " (+ as a utility)" : ""} | ${d.files.length} | ${d.inBase} | ${d.inTheme} |`),
].join("\n")

// ── 2. Literal geometry census ─────────────────────────────────────────────────────────────────
const FAMILIES = [
  { id: "height", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*(?:min-|max-)?h-(\d+(?:\.\d+)?|px|auto|full|screen|fit|min|max|svh|dvh)(?![\w-])/g, px: (v) => (isNaN(v) ? null : v * 4) },
  { id: "width", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*(?:min-|max-)?w-(\d+(?:\.\d+)?|px|full|fit|min|max|screen|xs|sm|md|lg|xl|2xl|3xl|4xl|5xl|6xl|7xl|prose)(?![\w-])/g, px: (v) => (isNaN(v) ? null : v * 4) },
  { id: "size", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*size-(\d+(?:\.\d+)?|px|full|auto|fit)(?![\w-])/g, px: (v) => (isNaN(v) ? null : v * 4) },
  { id: "padding", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*p[xytblrse]?-(\d+(?:\.\d+)?|px)(?![\w-])/g, px: (v) => (isNaN(v) ? null : v * 4) },
  { id: "margin", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*-?m[xytblrse]?-(\d+(?:\.\d+)?|px|auto)(?![\w-])/g, px: (v) => (isNaN(v) ? null : v * 4) },
  { id: "gap", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*(?:gap(?:-[xy])?|space-[xy])-(\d+(?:\.\d+)?|px)(?![\w-])/g, px: (v) => (isNaN(v) ? null : v * 4) },
  { id: "inset", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*-?(?:inset(?:-[xy])?|top|left|right|bottom|start|end)-(\d+(?:\.\d+)?|px|full|auto)(?![\w-])/g, px: (v) => (isNaN(v) ? null : v * 4) },
  { id: "radius", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*rounded(?:-[tblrse]{1,2})?(?:-(none|xs|sm|md|lg|xl|2xl|3xl|full))?(?![\w-])/g, px: () => null, value: (m) => m[1] ?? "(base)" },
  { id: "text-size", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*text-(2xs|xs|sm|base|lg|xl|2xl|3xl|4xl|size-inherit)(?![\w-])/g, px: () => null },
  { id: "font-weight", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*font-(normal|medium|semibold|bold)(?![\w-])/g, px: () => null },
  { id: "leading", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*leading-(\d+(?:\.\d+)?|none|tight|snug|normal|relaxed|loose|display)(?![\w-])/g, px: () => null },
  { id: "border-width", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*border(?:-[xytblrse])?-(\d+|dot)(?![\w-])/g, px: (v) => (isNaN(v) ? null : Number(v)) },
  { id: "ring-width", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*(?:ring|outline|ring-offset|outline-offset)-(\d+)(?![\w-])/g, px: (v) => Number(v) },
  { id: "opacity", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*opacity-(\d+)(?![\w-])/g, px: () => null },
  { id: "colour-alpha", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*(?:bg|text|border|ring|from|to|via|fill|stroke|shadow|outline|decoration)-([a-z][\w-]*\/\d+)(?![\w-])/g, px: () => null },
  { id: "hard-colour", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*(?:bg|text|border|ring|fill|stroke|from|to|via|outline|decoration|shadow)-(white|black|transparent|current|inherit)(?![\w-])/g, px: () => null },
  { id: "duration", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*(?:duration|delay)-(\d+)(?![\w-])/g, px: () => null },
  { id: "z-index", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*z-(\d+|auto)(?![\w-])/g, px: () => null },
  { id: "translate/scale", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*-?(?:translate(?:-[xy])?|scale(?:-[xy])?)-(\d+(?:\.\d+)?|px|full)(?![\w-])/g, px: () => null },
  { id: "line-clamp", re: /(?<![\w-])(?:[\w\[\]=:-]+:)*line-clamp-(\d+|none)(?![\w-])/g, px: () => null },
]

// Only class strings count: lines that contain a quoted or template string with a class-like token.
function classStrings(s) {
  const out = []
  const re = /(["'`])((?:\\.|(?!\1)[^\\])*)\1/g
  let m
  while ((m = re.exec(s))) if (/(?:^|\s)[a-z][\w-]*(?:-[\w.\/]+)/.test(m[2]) && !/^https?:|\.(tsx?|css|mjs)$/.test(m[2])) out.push(m[2])
  return out
}

const census = []
for (const fam of FAMILIES) {
  const byValue = new Map()
  for (const { f, s, story } of sources) {
    if (f.endsWith(".css")) continue
    for (const cls of classStrings(s)) {
      for (const m of cls.matchAll(fam.re)) {
        const raw = m[0].replace(/^(?:[\w\[\]=:-]+:)*/, "")
        if (/^(data|group-data|has|aria|group-has|not|peer-data|in-data)-/.test(raw)) continue
        const v = fam.value ? fam.value(m) : m[1]
        const e = byValue.get(v) ?? { value: v, uses: 0, storyUses: 0, files: new Set(), storyFiles: new Set(), forms: new Set() }
        if (story) {
          e.storyUses++
          e.storyFiles.add(rel(f))
        } else {
          e.uses++
          e.files.add(rel(f))
        }
        e.forms.add(raw)
        byValue.set(v, e)
      }
    }
  }
  const values = [...byValue.values()].sort((a, b) => b.files.size - a.files.size || b.uses - a.uses)
  census.push({ fam, values })
}

const numeric = (v) => /^\d+(?:\.\d+)?$/.test(v)
const censusTables = census
  .filter((c) => c.values.length)
  .map(({ fam, values }) => {
    const rows = values.map((e) => {
      const px = fam.px(e.value)
      const forms = [...e.forms].sort().slice(0, 8).join(" ") + (e.forms.size > 8 ? " …" : "")
      const files = [...e.files].map((x) => x.replace(/^packages\/ui\/src\//, "").replace(/^apps\/web\//, "app:")).slice(0, 5).join(", ") + (e.files.size > 5 ? ` (+${e.files.size - 5})` : "")
      return `| \`${e.value}\` | ${px == null ? "" : px + "px"} | ${e.uses} | ${e.files.size} | ${e.storyUses} | \`${forms.replace(/\|/g, "\\|")}\` | ${files} |`
    })
    return ["#### " + fam.id, "", "| Value | px | Uses (components) | Files | Uses (stories) | Forms seen | Where |", "|---|---|---|---|---|---|---|", ...rows].join("\n")
  })
  .join("\n\n")

// Token candidates. Two kinds: semantic geometry (a height, an icon size, a popover width, a
// disabled opacity: the number means something and a change request names it) and spacing
// rhythm (padding, margin, gap on the 4px grid, R2-40: expected to be written by hand).
const SEMANTIC = new Set(["height", "width", "size", "border-width", "ring-width", "opacity", "colour-alpha", "hard-colour", "translate/scale", "duration", "z-index"])
const RHYTHM = new Set(["padding", "margin", "gap", "inset"])
const GEOMETRY = new Set([...SEMANTIC, ...RHYTHM])
// A reset (min-w-0, border-0, ring-0, opacity-100, bg-transparent, text-current) names no value.
const isReset = (fam, v) => v === "0" || v === "100" && fam === "opacity" || ["transparent", "current", "inherit"].includes(v)
const pick = (set, min) =>
  census
    .filter((c) => set.has(c.fam.id))
    .flatMap((c) => c.values.filter((e) => e.files.size >= min && !isReset(c.fam.id, e.value) && (numeric(e.value) || c.fam.id === "colour-alpha" || c.fam.id === "hard-colour")).map((e) => ({ family: c.fam.id, ...e, px: c.fam.px(e.value) })))
    .sort((a, b) => b.files.size - a.files.size || b.uses - a.uses)
const candidates = pick(SEMANTIC, 3)
const rhythm = pick(RHYTHM, 8)
const candRows = (list) =>
  list.map((e) => {
    const where = [...e.files].map((x) => x.replace(/^packages\/ui\/src\//, "").replace(/^apps\/web\//, "app:")).slice(0, 4).join(", ") + (e.files.size > 4 ? ` (+${e.files.size - 4})` : "")
    return `| ${e.family} | \`${e.value}\` | ${e.px == null ? "" : e.px + "px"} | ${e.files.size} | ${e.uses} | \`${[...e.forms].sort().slice(0, 5).join(" ")}${e.forms.size > 5 ? " …" : ""}\` | ${where} |`
  })
const candHead = ["| Family | Value | px | Component files | Uses | Forms seen | Where |", "|---|---|---|---|---|---|---|"]
const candTable = [...candHead, ...candRows(candidates)].join("\n")
const rhythmTable = [...candHead, ...candRows(rhythm)].join("\n")

// ── 3. Upstream (base) for contrast ───────────────────────────────────────────────────────────
let upstreamLiterals = 0
for (const f of upstream) for (const cls of classStrings(read(f))) for (const fam of FAMILIES) if (GEOMETRY.has(fam.id)) upstreamLiterals += (cls.match(fam.re) ?? []).length
let paigeLiterals = 0
for (const { s, story, f } of sources) if (!story && !f.endsWith(".css")) for (const cls of classStrings(s)) for (const fam of FAMILIES) if (GEOMETRY.has(fam.id)) paigeLiterals += (cls.match(fam.re) ?? []).length

const totals = [
  `theme.css defines ${defs.length} variables (layers ${[...new Set(defs.map((d) => d.layer))].join(", ")}).`,
  `${inventory.filter((d) => d.uses > 0).length} are used in Paige code (directly or as a utility); ${baseOnly.length} only by the shadcn bases; ${themeOnly.length} are reached only through another variable; ${dead.length} are defined and never referenced anywhere.`,
  `Palette raws (layer 1) referenced outside theme.css: ${rawOutside.length}.`,
  `Hand-written numeric geometry utilities in Paige component code (not stories, not base): ${paigeLiterals}; in upstream shadcn base files: ${upstreamLiterals}.`,
  `Semantic values (a height, a size, a width, an opacity, an alpha) that recur in 3 or more component files with no token: ${candidates.length}. Spacing-rhythm values in 8 or more files: ${rhythm.length}.`,
].join(" ")

const out = [
  START,
  "",
  totals,
  "",
  "### Token candidates: semantic geometry written by hand in three or more component files",
  "",
  "Heights, sizes, widths, opacities, alphas and hard colours that recur across component files. Each is a change request (\"make controls 40px\", \"icons one step smaller\", \"menus wider\") that today touches every file in the row. Stories and the story-only folders are counted apart because a story may size a frame by hand.",
  "",
  candTable,
  "",
  "### Spacing rhythm written by hand in eight or more component files",
  "",
  "Padding, margin and gap on the 4px grid (R2-40). Writing these by hand is the rule, not a finding; the table is here so the few that carry meaning (a row's side padding, a card's inset, the gap between an icon and its label) can be named when the archetypes are.",
  "",
  rhythmTable,
  "",
  "### Never referenced",
  "",
  dead.length ? dead.map((d) => `- \`${d.name}\` (layer ${d.layer}) = \`${d.value}\``).join("\n") : "- none",
  "",
  "### Used only by the shadcn bases",
  "",
  baseOnly.length ? baseOnly.map((d) => `- \`${d.name}\` (layer ${d.layer}), ${d.inBase} use(s) in \`src/base\``).join("\n") : "- none",
  "",
  "### Palette raws used outside theme.css",
  "",
  rawOutside.length ? rawOutside.map((d) => `- \`${d.name}\` in ${d.files.join(", ")}`).join("\n") : "- none (every colour outside theme.css goes through a role)",
  "",
  "### Theme inventory",
  "",
  "Every variable theme.css defines. *Uses in Paige code* counts `var(--x)` and the utility classes the `@theme inline` block derives from it (`bg-x`, `p-x`, `rounded-x`…), in `packages/ui/src` (base excluded) and `apps/web`; *Uses in base* the same over `src/base`; *Inside theme.css* its references from other variables and `@apply` lines.",
  "",
  invTable,
  "",
  "### Literal geometry census",
  "",
  "Every numeric or named step the Paige layer writes by hand, by family and value. *Uses (components)* and *Files* exclude stories and the story-only folders; *Uses (stories)* counts those. *Forms seen* are the utilities as written, variants stripped.",
  "",
  censusTables,
  "",
  END,
].join("\n")

if (process.argv.includes("--print")) {
  console.log(out)
} else {
  const file = join(root, "TOKENS.md")
  const doc = existsSync(file) ? readFileSync(file, "utf8") : `# Tokens\n\n${START}\n${END}\n`
  const s0 = doc.indexOf(START.slice(0, 20))
  const e0 = doc.indexOf(END)
  if (s0 < 0 || e0 < 0) throw new Error("TOKENS.md has no tokens markers.")
  writeFileSync(file, doc.slice(0, s0) + out + doc.slice(e0 + END.length))
  console.log(`Tokens: ${defs.length} variables, ${candidates.length} candidates → TOKENS.md`)
}
