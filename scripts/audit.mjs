// npm run audit: the component scorecard and the vocabulary roll-ups (AUDIT.md, A-01).
// Reads every component file under packages/ui/src (not base, internal, lib, icons, schemas, or
// the story-only folders) and its story file, and writes three generated sections into AUDIT.md:
//   1. the scorecard: one row per file (section, components, axes and their values, docs shape,
//      stories, plays, level tag);
//   2. axes: each axis name (variant, tone, size…) with every component that uses it and the
//      value set each one gives it, so a word used for two different things is one row apart;
//   3. words: each value word (muted, quiet, soft…) with every component.axis that uses it.
// Everything is read from the source by regex, as catalog.mjs reads purpose lines: no Storybook
// server, no TypeScript program. Where that is approximate the column says so.
//   node scripts/audit.mjs            writes AUDIT.md between the audit markers
//   node scripts/audit.mjs --print    prints the sections instead
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative, sep } from "node:path"
import { fileURLToPath } from "node:url"

import { constMaps, cvaAxes, exportedComponents, namedUnions, propAxes, read, walk } from "./source-axes.mjs"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const src = join(root, "packages/ui/src")
const SECTION_ORDER = ["primitives", "components", "charts", "forms", "patterns", "shell", "vault", "admin", "setup", "templates", "labs"]
const START = "<!-- audit:start (generated by `npm run audit`; do not edit by hand) -->"
const END = "<!-- audit:end -->"
const pascal = (s) => s.split(/[-_]/).map((w) => w[0].toUpperCase() + w.slice(1)).join("")

function purposeOf(s, name) {
  return new RegExp(`/\\*\\*\\s*([^\\n]*?)\\s*\\*/\\n(?:export )?function ${name}\\b`).test(s)
}

/** Prop lines (approximate): `  name?: Type` inside type bodies, excluding object-literal values. */
function propDocs(s) {
  const lines = s.split("\n")
  let total = 0
  let documented = 0
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i]
    if (!/^\s{2,}(?:readonly\s+)?[a-z]\w*\??:\s+(?!["'`{(]|\w+\s*\()[A-Za-z"(\[{]/.test(l)) continue
    if (/^\s{2,}[a-z]\w*:\s*"/.test(l) || /=>/.test(l) && !/\?:/.test(l)) continue
    total++
    let j = i - 1
    while (j >= 0 && lines[j].trim() === "") j--
    if (j >= 0 && /\*\/\s*$/.test(lines[j])) documented++
  }
  return { total, documented }
}

function storyFacts(storyFile) {
  if (!existsSync(storyFile)) return null
  const s = read(storyFile)
  const stories = [...s.matchAll(/^export const (\w+)(?::\s*Story)?\s*=/gm)].map((m) => m[1])
  const plays = (s.match(/^\s*play:/gm) ?? []).length + (s.match(/\bplay\s*:\s*(?:async\s*)?\(/g) ?? []).length - (s.match(/^\s*play:\s*(?:async\s*)?\(/gm) ?? []).length
  const metaTags = /tags:\s*\[([^\]]*)\]/.exec(s)?.[1] ?? ""
  const tags = [...metaTags.matchAll(/"([^"]+)"/g)].map((m) => m[1])
  const level = tags.find((t) => /^level-\d$/.test(t)) ?? ""
  const tracking = tags.filter((t) => /^(r\d+-\d+|gaps-\d+|s-\d+)$/.test(t)).length
  const description = /description:\s*\{\s*component/.test(s)
  const argTypes = /argTypes:\s*\{/.test(s)
  const wireframe = /Wireframe|Anatomy/.test(s)
  return { stories: stories.length, plays, level, tracking, description, argTypes, wireframe }
}

const files = walk(src).sort()
const rows = []
for (const f of files) {
  const rel = relative(src, f).split(sep).join("/")
  const section = rel.split("/")[0]
  const s = read(f)
  const components = exportedComponents(s)
  if (!components.length) continue // a rules module, a hook file: not a component file
  const unions = namedUnions(s)
  const maps = constMaps(s)
  const axes = { ...propAxes(s, unions, maps) }
  for (const [k, v] of Object.entries(cvaAxes(s))) axes[k] = [...new Set([...(axes[k] ?? []), ...v])]
  for (const k of Object.keys(axes)) if (["className", "children", "id", "name", "label", "href", "value"].includes(k)) delete axes[k]
  const purposes = components.map((c) => purposeOf(s, c))
  const header = /^\/\* /m.test(s)
  const archetype = /@archetype\s+([A-Z]\w*)/.exec(s)?.[1] ?? ""
  const props = propDocs(s)
  const story = storyFacts(f.replace(/\.tsx?$/, ".stories.tsx"))
  const mdx = existsSync(f.replace(/\.tsx?$/, ".mdx"))
  const subsection = rel.split("/").slice(0, -1).map(pascal).join(" › ")
  // The component the file is named for leads the roll-ups (labs/components/item.tsx → Item, not ItemFrame).
  const own = pascal(rel.split("/").pop().replace(/\.tsx?$/, ""))
  const primary = components.includes(own) ? own : components[0]
  rows.push({ rel, section, subsection, components, primary, axes, purposes, header, archetype, props, story, mdx })
}
rows.sort((a, b) => SECTION_ORDER.indexOf(a.section) - SECTION_ORDER.indexOf(b.section) || a.rel.localeCompare(b.rel))

// ── 1. Scorecard ───────────────────────────────────────────────────────────────────────────────
const esc = (x) => String(x).replace(/\|/g, "\\|")
const fmtAxes = (axes) =>
  Object.entries(axes)
    .map(([k, v]) => `${k}: ${v.join(" · ")}`)
    .join("<br>")
const scorecard = [
  "| Section | File | Components | Archetype | Axes (name: values) | Purpose line | Prop docs (≈) | Stories | Plays | Story desc | MDX | Level |",
  "|---|---|---|---|---|---|---|---|---|---|---|---|",
  ...rows.map((r) => {
    const purpose = r.purposes.every(Boolean) ? "all" : r.purposes.some(Boolean) ? `${r.purposes.filter(Boolean).length}/${r.purposes.length}` : "none"
    const st = r.story
    return `| ${r.subsection} | \`${r.rel}\` | ${r.components.join(", ")} | ${r.archetype || "—"} | ${esc(fmtAxes(r.axes)) || "—"} | ${purpose} | ${r.props.documented}/${r.props.total} | ${st ? st.stories : "none"} | ${st ? st.plays : "—"} | ${st?.description ? "yes" : "—"} | ${r.mdx ? "yes" : "—"} | ${st?.level || "—"} |`
  }),
].join("\n")

// ── 2. Axes roll-up ────────────────────────────────────────────────────────────────────────────
// `kind` is left out of the roll-ups: it is a discriminant (TS-BAR §2) and is meant to differ per union.
const byAxis = new Map()
for (const r of rows)
  for (const [axis, values] of Object.entries(r.axes)) {
    if (axis === "kind") continue
    const list = byAxis.get(axis) ?? []
    list.push({ component: r.primary, values })
    byAxis.set(axis, list)
  }
const axisRows = [...byAxis.entries()]
  .filter(([, uses]) => uses.length > 1)
  .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
  .map(([axis, uses]) => {
    const sets = new Set(uses.map((u) => u.values.slice().sort().join("|")))
    return `| \`${axis}\` | ${uses.length} | ${sets.size} | ${uses.map((u) => `**${u.component}** ${u.values.join(" · ")}`).join("<br>")} |`
  })
const axesTable = ["| Axis | Components | Distinct value sets | Who gives it which values |", "|---|---|---|---|", ...axisRows].join("\n")

// ── 3. Words roll-up ───────────────────────────────────────────────────────────────────────────
const byWord = new Map()
for (const r of rows)
  for (const [axis, values] of Object.entries(r.axes)) {
    if (axis === "kind") continue
    for (const v of values) {
      if (/^(true|false|\d+|default|none)$/.test(v)) continue
      const list = byWord.get(v) ?? []
      list.push(`${r.primary}.${axis}`)
      byWord.set(v, list)
    }
  }
const wordRows = [...byWord.entries()]
  .filter(([, uses]) => uses.length > 1)
  .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
  .map(([word, uses]) => `| \`${word}\` | ${uses.length} | ${uses.join(", ")} |`)
const wordsTable = ["| Word | Uses | As | ", "|---|---|---|", ...wordRows].join("\n")

// ── Totals ─────────────────────────────────────────────────────────────────────────────────────
const withStory = rows.filter((r) => r.story)
const totals = [
  `${rows.length} component files, ${rows.reduce((n, r) => n + r.components.length, 0)} exported components.`,
  `Purpose line on every export: ${rows.filter((r) => r.purposes.every(Boolean)).length}; on none: ${rows.filter((r) => !r.purposes.some(Boolean)).length}.`,
  `Header comment: ${rows.filter((r) => r.header).length}; \`@archetype\` declared: ${rows.filter((r) => r.archetype).length}. Story file: ${withStory.length}. Story with a component description: ${withStory.filter((r) => r.story.description).length}. MDX page: ${rows.filter((r) => r.mdx).length}. Level tag: ${withStory.filter((r) => r.story.level).length}.`,
  `Stories: ${withStory.reduce((n, r) => n + r.story.stories, 0)}; plays: ${withStory.reduce((n, r) => n + r.story.plays, 0)}. Prop lines documented (≈): ${rows.reduce((n, r) => n + r.props.documented, 0)}/${rows.reduce((n, r) => n + r.props.total, 0)}.`,
  `Axes used by more than one component: ${axisRows.length}; value words used by more than one component.axis: ${wordRows.length}.`,
].join(" ")

const out = [
  START,
  "",
  totals,
  "",
  "### Scorecard",
  "",
  "Archetype is the header's `@archetype` (ARCHETYPES.md §7.2; `check:vocab` reads the same line). Prop docs counts `name?: Type` lines preceded by a `/** … */` line, over all such lines in the file (approximate: it reads the file, not the type). Stories and plays are counted from the story file. Level is the `level-n` meta tag (LEVELS.md); none carries one yet.",
  "",
  scorecard,
  "",
  "### Axes",
  "",
  "Every axis name used by more than one component, and the value set each one gives it. One axis with several distinct value sets is a word doing several jobs. `kind` is left out: a discriminant differs per union by design (TS-BAR §2).",
  "",
  axesTable,
  "",
  "### Words",
  "",
  "Every value word used by more than one `component.axis`. A word under axes with different meanings is the vocabulary problem in one row.",
  "",
  wordsTable,
  "",
  END,
].join("\n")

if (process.argv.includes("--print")) {
  console.log(out)
} else {
  const file = join(root, "AUDIT.md")
  const doc = existsSync(file) ? readFileSync(file, "utf8") : `# UI audit\n\n${START}\n${END}\n`
  const s0 = doc.indexOf(START.slice(0, 20))
  const e0 = doc.indexOf(END)
  if (s0 < 0 || e0 < 0) throw new Error("AUDIT.md has no audit markers.")
  writeFileSync(file, doc.slice(0, s0) + out + doc.slice(e0 + END.length))
  console.log(`Audit: ${rows.length} component files → AUDIT.md`)
}
