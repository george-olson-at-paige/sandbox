const walk = (dir) =>
  readdirSync(dir).flatMap((n) => {
    const p = join(dir, n)
    if (statSync(p).isDirectory()) return SKIP_DIRS.has(n) ? [] : walk(p)
    return /\.tsx?$/.test(n) && !/\.(stories|test)\.tsx?$/.test(n) ? [p] : []
  })
const rel = (f) => relative(src, f).split(sep).join("/")
const read = (f) => readFileSync(f, "utf8").replace(/\r\n/g, "\n")
/** Source with block, line and JSX comments removed, so a rule quoted in a header doesn't count. */
const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^[ \t]*\/\/.*$/gm, "").replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, "")
const inHomes = (file, homes) => homes.some((h) => (h.endsWith("/") ? file.startsWith(h) : file === h))
const layerOf = (file) => file.split("/")[0]
const count = (s, re) => (s.match(re) || []).length

const bases = readdirSync(join(src, "base")).filter((n) => n.endsWith(".tsx") && !/\.stories\./.test(n)).map((n) => n.replace(/\.tsx$/, "")).sort()
// Bases another base imports (sidebar → sheet, toggle-group → toggle, field → label): upstream
// internals, kept as long as their importer is, whether or not Paige code names them.
const baseInternal = new Map()
for (const b of bases)
  for (const m of stripComments(read(join(src, "base", `${b}.tsx`))).matchAll(/from "\.\/([\w-]+)"/g))
    baseInternal.set(m[1], [...(baseInternal.get(m[1]) ?? []), b])
const files = walk(src).map((f) => ({ file: rel(f), source: stripComments(read(f)) }))

/* ---------- facts per file ---------- */

/** Relative imports of a file, resolved to src-relative paths without extension ("components/display/card"). */
const localImports = (f) =>
  [...f.source.matchAll(/from "(\.{1,2}\/[^"]+)"/g)].map((m) => {
    const parts = dirname(f.file).split("/").filter((p) => p && p !== ".")
    for (const seg of m[1].split("/")) {
      if (seg === "..") parts.pop()
      else if (seg !== ".") parts.push(seg)
    }
    return parts.join("/").replace(/\.tsx?$/, "")
  })

for (const f of files) {
  f.layer = layerOf(f.file)
  f.imports = localImports(f)
  f.baseImports = [...f.source.matchAll(/from "(?:\.\.\/)+base\/([\w-]+)"/g)].map((m) => m[1])
  f.raw = {}
  for (const tag of Object.keys(RAW)) {
    const n = count(f.source, new RegExp(`<${tag}(?=[\\s/>])`, "g"))
    if (n && !inHomes(f.file, RAW[tag].homes)) f.raw[tag] = n
  }
  f.signals = {}
  for (const s of SIGNALS) {
    const scope = s.skipLine ? f.source.split("\n").filter((l) => !s.skipLine.test(l)).join("\n") : f.source
    const n = count(scope, s.re)
    if (n && !inHomes(f.file, s.homes)) f.signals[s.id] = n
  }
}
// A raw <button> in a file that never says how it focuses: the browser's default ring, not R15-17's.
// The focus helpers (control.ts, popover-surface.ts) count, as does a class constant imported from
// a Paige file that composes one (QuickAdd's pills come from PersonPicker's `personPill`).
const FOCUS_HELPER = /focus-ring|cardFocus|controlFocus|\bpressable\b|\bmenuItem\b|popoverItem|focus-visible:/
const bySrcPath = new Map(files.map((f) => [f.file.replace(/\.tsx?$/, ""), f]))
const namedImports = (f) =>
  [...f.source.matchAll(/import\s*\{([^}]*)\}\s*from\s*"(\.{1,2}\/[^"]+)"/g)].flatMap((m) => {
    const target = localImports({ file: f.file, source: `from "${m[2]}"` })[0]
    return m[1].split(",").map((s) => s.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0]).filter(Boolean).map((name) => [name, target])
  })
const composesFocus = (target, name) => {
  if (!target) return false
  const alias = new RegExp(`\\b(\\w+)\\s+as\\s+${name}\\b`).exec(target.source)
  const decl = new RegExp(`(?:const|let)\\s+${alias ? alias[1] : name}\\s*=\\s*([^\\n]*)`).exec(target.source)
  return Boolean(decl && FOCUS_HELPER.test(decl[1]))
}
const saysHowItFocuses = (f) => FOCUS_HELPER.test(f.source) || namedImports(f).some(([name, path]) => composesFocus(bySrcPath.get(path), name))
for (const f of files) if (f.raw.button && !saysHowItFocuses(f)) f.signals["button-no-focus-style"] = f.raw.button

/* ---------- 1. bases ---------- */

/* A file inherits a base by importing it, or by importing a Paige wrapper that does (Panel over
   Card over base/card): upper layers may not import base (check:layers), so the wrapper is the
   right path there. */
const baseRows = bases.map((b) => {
  const direct = files.filter((f) => f.baseImports.includes(b))
  const wrapperPaths = new Set(direct.map((f) => f.file.replace(/\.tsx?$/, "")))
  const via = files.filter((f) => !f.baseImports.includes(b) && f.imports.some((i) => wrapperPaths.has(i)))
  const importers = direct.map((f) => f.file)
  const viaWrapper = via.map((f) => f.file)
  const sameJob = (SAME_JOB[b] ?? []).filter((p) => existsSync(join(src, p)))
  const notWrapping = sameJob.filter((p) => !importers.includes(p) && !viaWrapper.includes(p))
  const inRegistry = REGISTRY.includes(b)
  const usedByBase = baseInternal.get(b) ?? []
  return { b, importers, viaWrapper, sameJob, notWrapping, inRegistry, usedByBase }
})

/* ---------- 2. registry components not added ---------- */

const LOOKS_LIKE = {
  "combobox": (f) => (f.signals["arrow-keys"] || f.signals["own-popover"]) && /<input|from "[./]+\/components\/inputs\/input"|\bInput\b/.test(f.source),
  "command": (f) => f.signals["arrow-keys"] && /role="listbox"|role="option"|aria-activedescendant/.test(f.source),
  "input-group": (f) => f.signals["input-adornment"] && /<input|\bInput\b|<select|\bSelect\b/.test(f.source),
  "kbd": (f) => f.raw.kbd || /<kbd/.test(f.source),
  "empty": (f) => /\b(?:empty|Empty)(?:State|Row|Message|Body)\b|data-slot="empty/.test(f.source),
  "pagination": (f) => /\b[Pp]agination\b|aria-label="[Pp]agination"/.test(f.source),
  "breadcrumb": (f) => /\b[Bb]readcrumb\b/.test(f.source),
  "button-group": (f) => /\brounded-l-\w+\b[\s\S]{0,200}\brounded-r-\w+\b|\b-ml-px\b/.test(f.source),
  "scroll-area": (f) => /\bscrollbar-(?:thin|below-header)\b/.test(f.source),
  "sonner": (f) => /\btoast\b/i.test(f.source),
  "accordion": (f) => /from "[./]+\/components\/display\/collapsible"|\bCollapsible\b/.test(f.source) && /\.map\(/.test(f.source),
  "slider": (f) => /type="range"/.test(f.source),
  "aspect-ratio": (f) => /\baspect-(?:square|video|\[)/.test(f.source),
  "hover-card": (f) => /onMouseEnter[\s\S]{0,400}(?:Popover|absolute)/.test(f.source),
  "drawer": (f) => /\bfixed\b[^"]*\b(?:bottom-0|inset-x-0)\b[^"]*\brounded-t/.test(f.source),
}
const notAdded = REGISTRY.filter((r) => !bases.includes(r)).map((r) => ({
  r,
  looks: LOOKS_LIKE[r] ? files.filter((f) => LOOKS_LIKE[r](f)).map((f) => f.file) : null,
}))

/* ---------- render ---------- */

const code = (s) => `\`${s}\``
const list = (xs, max = 6) => (xs.length ? xs.slice(0, max).map(code).join(", ") + (xs.length > max ? ` (+${xs.length - max})` : "") : "—")
const totals = {
  files: files.length,
  bases: bases.length,
  basesUnused: baseRows.filter((r) => r.importers.length === 0 && !r.usedByBase.length).length,
  notWrapping: baseRows.reduce((n, r) => n + r.notWrapping.length, 0),
  notAdded: notAdded.length,
  notAddedWithCopies: notAdded.filter((r) => r.looks && r.looks.length).length,
  rawFiles: files.filter((f) => Object.keys(f.raw).length).length,
  rawCount: files.reduce((n, f) => n + Object.values(f.raw).reduce((a, b) => a + b, 0), 0),
  signalFiles: files.filter((f) => Object.keys(f.signals).length).length,
}

const out = []
out.push(START, "")
out.push(
  `${totals.files} Paige component files (internal helpers included; base, stories and the story-only folders excluded). ${totals.bases} shadcn bases in \`src/base\`: ${totals.basesUnused} with no Paige importer; ${totals.notWrapping} Paige file(s) that do a base's job without importing it. ${totals.notAdded} registry components not added, ${totals.notAddedWithCopies} of them with Paige markup that looks like a hand-rolled copy. Raw elements outside their home: ${totals.rawCount} in ${totals.rawFiles} files. Files with at least one out-of-area signal: ${totals.signalFiles}.`,
  "",
)

out.push("### Bases: who inherits them", "")
out.push("Every upstream file in `src/base`, the Paige files that import it directly, the files that reach it through one of those (a Panel over Card over `base/card`: the right path above the components layer), and the Paige files that do the same job through neither (`SAME_JOB` in the script names the pairs). A base with no importer is maintenance paid for nothing; a same-job file that doesn't inherit is a copy that pays its own.", "")
out.push("| Base | Imported by | Reached through a wrapper by | Same job, inheriting nothing | Note |", "|---|---|---|---|---|")
for (const r of baseRows) {
  const note = !r.inRegistry ? "not in the registry list (local or renamed)" : r.importers.length === 0 ? (r.usedByBase.length ? `upstream internal: imported by base ${list(r.usedByBase)}` : "**no Paige importer**") : r.notWrapping.length ? "**copy beside the base**" : ""
  out.push(`| \`${r.b}\` | ${list(r.importers, 4)} | ${list(r.viaWrapper, 5)} | ${list(r.notWrapping)} | ${note} |`)
}
out.push("")

out.push("### Registry components not added", "")
out.push("shadcn components the package hasn't run `ui:add` for. *Looks like a copy* lists Paige files whose markup matches a heuristic for that component (arrow keys over an input for combobox, `pl-9` beside an input for input-group…); an empty cell with a heuristic means nothing matched, a dash means no heuristic.", "")
out.push("| Component | Looks like a copy in | Heuristic |", "|---|---|---|")
for (const r of notAdded) out.push(`| \`${r.r}\` | ${r.looks === null ? "—" : list(r.looks, 8)} | ${LOOKS_LIKE[r.r] ? "yes" : "none"} |`)
out.push("")

out.push("### Raw elements outside their home", "")
out.push("A `<button>`, `<input>`, `<a>`… written in a file that isn't the element's home component (`RAW` in the script lists the homes). Each is either a reason to reach for the component, or a reason the home should grow a prop.", "")
out.push("| Element | Home | Files (count) |", "|---|---|---|")
for (const tag of Object.keys(RAW)) {
  const hits = files.filter((f) => f.raw[tag]).map((f) => `\`${f.file}\` (${f.raw[tag]})`)
  if (hits.length) out.push(`| \`<${tag}>\` | ${RAW[tag].home} | ${hits.join(", ")} |`)
}
out.push("")

out.push("### Out-of-area signals", "")
out.push("Patterns that belong to one component, found in another (`SIGNALS` in the script). A file in a signal's home list is not counted.", "")
out.push("| Signal | Belongs to | Files (count) |", "|---|---|---|")
for (const s of [...SIGNALS, { id: "button-no-focus-style", home: "a shared pressable reset (focus, cursor, disabled) or Button" }]) {
  const hits = files.filter((f) => f.signals[s.id]).map((f) => `\`${f.file}\` (${f.signals[s.id]})`)
  if (hits.length) out.push(`| ${s.id} | ${s.home} | ${hits.join(", ")} |`)
}
out.push("")

out.push("### By file", "")
out.push("Every file with a base import, a raw element or a signal. Files with none are the quiet majority and aren't listed.", "")
out.push("| Layer | File | Bases imported | Raw elements | Signals |", "|---|---|---|---|---|")
const fmt = (o) => Object.entries(o).map(([k, v]) => `${k} ×${v}`).join(", ") || "—"
for (const f of files) {
  if (!f.baseImports.length && !Object.keys(f.raw).length && !Object.keys(f.signals).length) continue
  out.push(`| ${f.layer} | \`${f.file}\` | ${list([...new Set(f.baseImports)])} | ${fmt(f.raw)} | ${fmt(f.signals)} |`)
}
out.push("", END)

const text = out.join("\n")
if (process.argv.includes("--print")) {
  console.log(text)
} else {
  const target = join(root, "REUSE.md")
  const current = existsSync(target) ? read(target) : "# Reuse\n\n" + START + "\n" + END + "\n"
  const s = current.indexOf("<!-- reuse:start")
  const e = current.indexOf(END)
  const next = s >= 0 && e >= 0 ? current.slice(0, s) + text + current.slice(e + END.length) : current + "\n" + text + "\n"
  writeFileSync(target, next)
  console.log(`Reuse: ${totals.bases} bases, ${totals.notWrapping} same-job copies, ${totals.rawCount} raw elements, ${totals.signalFiles} files with signals → REUSE.md`)
}
