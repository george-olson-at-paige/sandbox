// npm run audit:reuse: where the Paige layer inherits shadcn's maintenance and where it built its
// own (REUSE.md). Reads every Paige component file (not base, stories, lib, icons, schemas, or the
// story-only folders; internal helpers included) and writes four generated sections:
//   1. bases: every upstream file in src/base, the Paige files that import it, and the Paige
//      component with the same job that does not;
//   2. not added: shadcn registry components the package hasn't added, with the Paige files whose
//      markup looks like a hand-rolled copy of them;
//   3. raw elements: <button>, <input>, <a>… written in a file that is not that element's home;
//   4. signals: patterns a component has that belong to another component (a spinner outside
//      Spinner, arrow-key handling outside the menus, a clickable div, a local cva…).
// Everything is read by regex after comments are stripped; a row is a question for a reader, not
// a verdict. The verdicts (keep, wrap, adopt) are the written findings above the markers.
//   node scripts/audit-reuse.mjs            writes REUSE.md between the reuse markers
//   node scripts/audit-reuse.mjs --print    prints the sections instead
