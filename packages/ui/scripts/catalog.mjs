// "I need… → use…" catalog (R1-30). Reads Storybook's index (the running dev server's
// /index.json, else storybook-static/index.json) and, for each entry in the importable sections
// (Primitives through Templates, R7-01), the one-line `/** … */` purpose directly above the component's function.
// Writes the table into CATALOG.md between the catalog markers.
//   npm run catalog -w packages/ui            (dev server on 6106 if up, else the static build)
//   npm run catalog -w packages/ui -- --static (static build only)
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..")
// Charts show under Components › Charts (the folder stays its own tier; .storybook/main.ts titles it), so no root of their own here.
// Auth's views are stories on the AuthPage template (R18); a row appears once an auth part has a module of its own.
const SECTIONS = ["Primitives", "Components", "Forms", "Patterns", "Shell", "Vault", "Admin", "Setup", "Auth", "Templates"]
/** Story files whose component lives under another name. */
const OVERRIDES = {
  "Components/Navigation/TabsPill": ["src/components/navigation/tabs-pill.tsx", "TabsPillList"],
  "Components/Navigation/TabsLine": ["src/components/navigation/tabs-line.tsx", "TabsLineList"],
  // R21-14: the Journeys page is its parts; the view is what a reader comes for.
  "Admin/Pages/Journeys": ["src/admin/pages/journeys.tsx", "JourneysView"],
  // dag-legend.stories.tsx shows the legend from dag-status.tsx (R10-12).
  "Charts/DagLegend": ["src/charts/dag-status.tsx", "DagLegend"],
  // R15-15, R15-11: the partner's offers dialog and its rev share section (and the defaults' form).
  "Admin/PartnerOffers": ["src/admin/partner-offers.tsx", "ManageOffersDialog"],
  "Admin/RevShare": ["src/admin/rev-share.tsx", "PartnerRevShareSection"],
  // R19-05: the part is Toast (what a person sees); the mounted component is the Toaster, the call is `toast`.
  "Components/Feedback/Toast": ["src/components/feedback/toast.tsx", "Toaster"],
}
const START = "<!-- catalog:start (generated by `npm run catalog -w packages/ui`; do not edit by hand) -->"
const END = "<!-- catalog:end -->"

/** The dev server to read: STORYBOOK_URL (another worktree's port), else 6106 (as run-plays.mjs). */
const BASE = (process.env.STORYBOOK_URL ?? "http://localhost:6106").replace(/\/$/, "")

async function loadIndex() {
  if (!process.argv.includes("--static")) {
    try {
      const res = await fetch(`${BASE}/index.json`, { signal: AbortSignal.timeout(3000) })
      const text = await res.text()
      if (res.ok && text.startsWith("{")) return { index: JSON.parse(text), from: `dev server (${BASE})` }
    } catch {
      /* fall through to the static build */
    }
  }
  const file = join(pkg, "storybook-static", "index.json")
  if (!existsSync(file)) throw new Error("No Storybook index: start Storybook (6106) or run `npm run build-storybook -w packages/ui`.")
  return { index: JSON.parse(readFileSync(file, "utf8")), from: "storybook-static/index.json" }
}

function purposeOf(file, name) {
  if (!existsSync(file)) return null
  const src = readFileSync(file, "utf8").replace(/\r\n/g, "\n")
  const m = new RegExp(`/\\*\\*\\s*([^\\n]*?)\\s*\\*/\\n(?:export )?function ${name}\\b`).exec(src)
  return m ? m[1] : null
}

const { index, from } = await loadIndex()
const byTitle = new Map()
for (const e of Object.values(index.entries)) {
  const section = e.title.split("/")[0]
  if (!SECTIONS.includes(section)) continue
  const t = byTitle.get(e.title) ?? { title: e.title, section, layer: e.title.split("/").slice(0, -1).join(" › "), name: e.title.split("/").pop(), importPath: null, docsId: null }
  if (e.type === "docs") t.docsId = e.id
  if (e.type === "story" && !t.importPath) t.importPath = e.importPath
  byTitle.set(e.title, t)
}

const rows = []
const missing = []
for (const t of byTitle.values()) {
  const [rel, fn] = OVERRIDES[t.title] ?? [t.importPath?.replace(/^\.\//, "").replace(/\.stories\.tsx$/, ".tsx"), t.name]
  if (!rel) continue
  const file = join(pkg, rel)
  if (!existsSync(file)) continue // a story with no component of its own
  // A module of list parts has no component of its title's name; its page setup carries the line (R17-06: peoplePage for People).
  const purpose = purposeOf(file, fn) ?? purposeOf(file, `${fn[0].toLowerCase()}${fn.slice(1)}Page`)
  if (!purpose) missing.push(`${t.title} (${rel}: no /** purpose */ above function ${fn})`)
  const imp = rel.replace(/^src\//, "@paige/ui/").replace(/\.tsx?$/, "")
  rows.push({ ...t, purpose: purpose ?? "(no purpose line)", imp, story: t.docsId ? `?path=/docs/${t.docsId}` : "" })
}
rows.sort((a, b) => SECTIONS.indexOf(a.section) - SECTIONS.indexOf(b.section) || a.layer.localeCompare(b.layer) || a.name.localeCompare(b.name))

const esc = (s) => s.replace(/\|/g, "\\|")
const table = [
  "| I need… | Use | Layer | Import | Story |",
  "|---|---|---|---|---|",
  ...rows.map((r) => `| ${esc(r.purpose)} | **${r.name}** | ${r.layer} | \`${r.imp}\` | \`${r.story}\` |`),
].join("\n")
const base = Object.values(index.entries)
  .filter((e) => e.type === "docs" && e.title.startsWith("Base/"))
  .map((e) => e.title.slice(5))
  .sort()
const block = [
  START,
  "",
  `${rows.length} components. Story links are paths on the Storybook URL (http://localhost:6106/${rows[0]?.story ?? ""}).`,
  "",
  table,
  "",
  `Base (upstream shadcn, reference only; imported only by \`src/components\` and \`src/forms\`): ${base.join(", ")}.`,
  "",
  END,
].join("\n")

const claude = join(pkg, "CATALOG.md") // R17-14: the catalog has its own file
const doc = readFileSync(claude, "utf8")
const s = doc.indexOf(START.slice(0, 20))
const e = doc.indexOf(END)
if (s < 0 || e < 0) throw new Error("CATALOG.md has no catalog markers.")
writeFileSync(claude, doc.slice(0, s) + block + doc.slice(e + END.length))
console.log(`Catalog: ${rows.length} components from ${from} → CATALOG.md`)
if (missing.length) {
  console.log(`Missing purpose lines:\n  ${missing.join("\n  ")}`)
  process.exitCode = 1
}
